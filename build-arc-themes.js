/**
 * Karibase ARC Theme Builder
 *
 * Generates one Karibase theme stylesheet per ARC Starter Templates kit —
 * WITHOUT touching the plugin (read-only consumption of its manifest):
 *
 *   src/styles/themes/karibase-theme-<kit>.css   theme preset per kit
 *   src/styles/themes/index.css                  @import entry point
 *   src/config/arc-templates.js                  resolved token registry
 *
 * Token resolution mirrors Arc_ST_Templates::design_system() exactly so the
 * generated themes match what WordPress renders on .arc-tpl:
 *   demo kit colors/fonts  >  home.html @theme vars  >  Karibase UCLA defaults
 *
 * Usage:
 *   node build-arc-themes.js                       # default plugins dir
 *   PLUGINS_DIR=/path/to/wp-content/plugins node build-arc-themes.js
 */

