const isHex = (v) => /^#[0-9a-fA-F]{3,8}$/.test(String(v || ''))
const pickColor = (v, fallback) => (isHex(v) ? v : fallback)
const pickFont = (v, fallback) => {
  const clean = String(v || '')
    .trim()
    .replace(/^['"]+|['"]+$/g, '')
    .replace(/[^A-Za-z0-9 -]/g, '')
  return clean || fallback
}

function themeValue(html, name) {
  const match = html.match(new RegExp(`--${name}\\s*:\\s*(#[0-9a-fA-F]{3,8})\\s*;`))
  return match ? match[1] : ''
}

function themeFont(html, name) {
  const match = html.match(new RegExp(`--${name}\\s*:\\s*([^,;]+)`))
  return match ? match[1] : ''
}

/**
 * Resolve a demo kit into design tokens (kit meta > html vars > defaults).
 * Mirrors Arc_ST_Templates::design_system() in the plugin.
 */
function resolveKit(demo, html) {
  const kit = demo.kit || {}
  const kitColors = {}
  for (const item of kit.colors || []) {
    const parts = String(item._id || '').split('_')
    const key = parts.length > 1 ? parts[parts.length - 1] : ''
    if (key && item.color) kitColors[key] = String(item.color)
  }

  const kitFonts = [null, null]
  for (const item of kit.fonts || []) {
    const id = String(item._id || '')
    const m = id.match(/(?:^|_)(body|heading)$/)
    if (m && item.typography_font_family) {
      kitFonts[m[1] === 'body' ? 0 : 1] = pickFont(item.typography_font_family, 'Inter')
    }
  }

  const body = kitFonts[0] || pickFont(themeFont(html, 'font-sans'), DEFAULTS.body)
  const heading = kitFonts[1] || pickFont(themeFont(html, 'font-display'), body) || body

  return {
    colors: {
      brand: pickColor(kitColors.brand ?? themeValue(html, 'color-brand'), DEFAULTS.brand),
      dark: pickColor(kitColors.dark ?? themeValue(html, 'color-brand-dark'), DEFAULTS.dark),
      navy: pickColor(kitColors.navy ?? themeValue(html, 'color-navy'), DEFAULTS.navy),
      accent: pickColor(
        kitColors.accent ?? kitColors.gold ?? themeValue(html, 'color-gold'),
        DEFAULTS.accent
      ),
      surface: pickColor(kitColors.mint ?? themeValue(html, 'color-cream'), DEFAULTS.surface)
    },
    fonts: { body, heading }
  }
}

