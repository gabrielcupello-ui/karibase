function registryModule(kits) {
  const entries = Object.entries(kits)
    .map(
      ([slug, t]) => `  '${slug}': {
    name: '${t.name.replace(/'/g, "\\'")}',
    home: '${t.home}',
    colors: { brand: '${t.colors.brand}', dark: '${t.colors.dark}', navy: '${t.colors.navy}', accent: '${t.colors.accent}', surface: '${t.colors.surface}' },
    fonts: { body: '${t.fonts.body.replace(/'/g, "\\'")}', heading: '${t.fonts.heading.replace(/'/g, "\\'")}' },
    theme: '${t.theme}'
  }`
    )
    .join(',\n')

  return `/**
 * Karibase ARC Templates Registry
 * ${GENERATED_BANNER}
 *
 * Resolved design tokens for every ARC Starter Templates kit — the same values
 * Arc_ST_Templates::design_system() injects on .arc-tpl in WordPress.
 * Regenerate with: npm run build:themes
 */

export const arcTemplates = {
${entries}
}

/** All kit slugs. */
export const arcTemplateSlugs = Object.keys(arcTemplates)

/** Resolved tokens for a kit slug (undefined when unknown). */
export function getArcTemplate(slug) {
  return arcTemplates[slug]
}

/** Theme stylesheet path relative to src/styles/. */
export function arcThemePath(slug) {
  const tpl = arcTemplates[slug]
  return tpl ? tpl.theme : ''
}

export default arcTemplates
`
}

async function main() {
  console.log('Karibase — building ARC template themes')
  console.log(`Manifest: ${MANIFEST}`)

  if (!existsSync(MANIFEST)) {
    console.error(`Manifest not found: ${MANIFEST}`)
    console.error('Set PLUGINS_DIR to your wp-content/plugins path.')
    process.exit(1)
  }

  const manifest = JSON.parse(await readFile(MANIFEST, 'utf8'))
  const demos = manifest.demos || {}

  await rm(OUT_THEMES, { recursive: true, force: true })
  await mkdir(OUT_THEMES, { recursive: true })

  const kits = {}
  const imports = []
  for (const [slug, demo] of Object.entries(demos)) {
    const homeSlug = demo.home || `${slug}-home`
    const homeMeta = (manifest.templates || {})[homeSlug]
    const homeFile = homeMeta ? homeMeta.file : `${slug}/home.html`
    const homePath = path.join(TEMPLATES_DIR, homeFile)
    const html = existsSync(homePath) ? await readFile(homePath, 'utf8') : ''

    const tokens = resolveKit(demo, html)
    const name = demo.name || prettyName(slug)

    kits[slug] = { name, home: homeSlug, ...tokens, theme: `themes/karibase-theme-${slug}.css` }

    const file = `karibase-theme-${slug}.css`
    await writeFile(path.join(OUT_THEMES, file), themeCss(slug, { name }, tokens))
    imports.push(`@import url('./${file}'); /* ${name} */`)
    console.log(
      `  ${slug}: brand ${tokens.colors.brand} · accent ${tokens.colors.accent} · ${tokens.fonts.body}/${tokens.fonts.heading}`
    )
  }

  await writeFile(
    path.join(OUT_THEMES, 'index.css'),
    `/*!
 * Karibase ARC Themes — ${GENERATED_BANNER}
 * One preset per ARC Starter Templates kit. Load a single theme file for a
 * branded site, or this index to register them all.
 * Regenerate with: npm run build:themes
 */

${imports.join('\n')}
`
  )

  await mkdir(path.dirname(OUT_REGISTRY), { recursive: true })
  await writeFile(OUT_REGISTRY, registryModule(kits))
  await writeFile(OUT_REGISTRY_JSON, JSON.stringify({ generated: new Date().toISOString(), templates: kits }, null, 2))

  console.log(`\nDone: ${Object.keys(kits).length} themes`)
  console.log(`Themes:   ${path.relative(ROOT, OUT_THEMES)}`)
  console.log(`Registry: ${path.relative(ROOT, OUT_REGISTRY)}`)
}

main().catch((err) => {
  console.error('Theme build failed:', err)
  process.exit(1)
})
