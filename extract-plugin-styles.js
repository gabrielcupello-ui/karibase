#!/usr/bin/env node

/**
 * Karibase Plugin Styles Extractor
 *
 * Extracts every stylesheet owned by the team WordPress plugins into the
 * framework — WITHOUT touching the plugins (read-only extraction):
 *
 *   1. Copies each plugin's *.css files     → src/styles/plugins/<plugin>/...
 *   2. Extracts inline <style> blocks from  → src/styles/plugins/<plugin>/inline/
 *      PHP files (admin pages, templates)
 *   3. Generates src/config/plugins.js      → registry consumed by the app/WP layer
 *   4. Generates src/styles/karibase-plugins.css → single @import entry point
 *
 * Classification:
 *   source  — authored stylesheets, always imported by the index
 *   vendor  — compiled/minified/third-party (tailwind.css, *.min.css, vendor/)
 *   inline  — <style> blocks lifted out of PHP files
 *   dynamic — inline blocks containing PHP interpolation (listed, not imported)
 *
 * Usage:
 *   node extract-plugin-styles.js                    # default plugins dir
 *   PLUGINS_DIR=/path/to/wp-content/plugins node extract-plugin-styles.js
 */

import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(fileURLToPath(import.meta.url))
const PLUGINS_DIR =
  process.env.PLUGINS_DIR || 'C:/laragon/www/Prwebsie/wp-content/plugins'
const OUT_STYLES = path.join(ROOT, 'src/styles/plugins')
const OUT_INDEX = path.join(ROOT, 'src/styles/karibase-plugins.css')
const OUT_REGISTRY = path.join(ROOT, 'src/config/plugins.js')
const OUT_REGISTRY_JSON = path.join(ROOT, 'src/config/plugins.json')

const SKIP_DIRS = new Set(['node_modules', '.git', '.svn'])
const GENERATED_BANNER = 'Generated by extract-plugin-styles.js — do not edit by hand.'

const slugify = (value) =>
  value
    .replace(/\\/g, '/')
    .replace(/\.(php|css)$/i, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase()

async function* walk(dir) {
  let entries
  try {
    entries = await readdir(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(full)
    else if (entry.isFile()) yield full
  }
}

/** A directory is a plugin when it ships at least one PHP file. */
async function isPluginDir(dir) {
  for await (const file of walk(dir)) {
    if (file.endsWith('.php')) return true
  }
  return false
}

function classifyCss(relPath) {
  const normalized = relPath.replace(/\\/g, '/').toLowerCase()
  const base = path.basename(normalized)
  if (normalized.includes('/vendor/')) return 'vendor'
  if (base.endsWith('.min.css')) return 'vendor'
  if (base === 'tailwind.css') return 'vendor' // compiled Tailwind build output
  return 'source'
}

async function extractPlugin(pluginDir) {
  const slug = path.basename(pluginDir)
  const styles = []
  const inline = []

  for await (const file of walk(pluginDir)) {
    const rel = path.relative(pluginDir, file).replace(/\\/g, '/')
    if (/\.css$/i.test(file)) {
      // Skip minified duplicates when the authored source ships alongside.
      if (/\.min\.css$/i.test(file)) {
        const source = file.replace(/\.min\.css$/i, '.css')
        if (existsSync(source)) continue
      }
      const target = path.join(OUT_STYLES, slug, rel)
      const css = await readFile(file, 'utf8')
      await mkdir(path.dirname(target), { recursive: true })
      await writeFile(
        target,
        `/* ${GENERATED_BANNER}\n * Plugin: ${slug}\n * Source: ${rel}\n */\n\n${css}`
      )
      styles.push({ file: `plugins/${slug}/${rel}`, kind: classifyCss(rel), source: rel })
    } else if (/\.php$/i.test(file)) {
      const php = await readFile(file, 'utf8')
      const blocks = php.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)
      let index = 0
      for (const block of blocks) {
        index += 1
        const css = block[1].trim()
        if (!css) continue
        const dynamic = /<\?|\{\$|\$[a-zA-Z_]/.test(css)
        const name = `inline/${slugify(rel)}${index > 1 ? `-${index}` : ''}.css`
        const target = path.join(OUT_STYLES, slug, name)
        await mkdir(path.dirname(target), { recursive: true })
        await writeFile(
          target,
          `/* ${GENERATED_BANNER}\n * Plugin: ${slug}\n * Source: ${rel} <style> block #${index}${dynamic ? '\n * WARNING: contains PHP interpolation — verify selectors before use.' : ''}\n */\n\n${css}\n`
        )
        inline.push({ file: `plugins/${slug}/${name}`, kind: 'inline', dynamic, source: `${rel}#${index}` })
      }
    }
  }

  return { slug, styles, inline }
}

function registryModule(plugins) {
  const entries = Object.entries(plugins)
    .map(([slug, data]) => {
      const styles = data.styles
        .map((s) => `      { file: '${s.file}', kind: '${s.kind}', source: '${s.source}' }`)
        .join(',\n')
      const inline = data.inline
        .map(
          (s) =>
            `      { file: '${s.file}', kind: 'inline', dynamic: ${s.dynamic}, source: '${s.source}' }`
        )
        .join(',\n')
      return `  '${slug}': {
    name: '${data.name}',
    dir: '${slug}',
    styles: [
${styles}
    ],
    inlineStyles: [
${inline}
    ]
  }`
    })
    .join(',\n')

  return `/**
 * Karibase Plugin Styles Registry
 * ${GENERATED_BANNER}
 *
 * Maps every extracted stylesheet back to the WordPress plugin that owns it.
 * Regenerate with: npm run extract:plugins
 */

export const plugins = {
${entries}
}

/** Plugin slugs with extracted styles. */
export const pluginSlugs = Object.keys(plugins)

/** All stylesheets for a plugin (source + vendor + inline). */
export function pluginStyles(slug) {
  const plugin = plugins[slug]
  return plugin ? [...plugin.styles, ...plugin.inlineStyles] : []
}

/** Only the authored (non-vendor, non-dynamic) stylesheets for a plugin. */
export function pluginSourceStyles(slug) {
  return pluginStyles(slug).filter((s) => s.kind === 'source' || (s.kind === 'inline' && !s.dynamic))
}

/** Path for an extracted file, relative to src/styles/ (same base as karibase-plugins.css). */
export function pluginStylePath(file) {
  return file
}

export default plugins
`
}

function indexCss(plugins) {
  const imports = []
  for (const [slug, data] of Object.entries(plugins)) {
    const files = [...data.styles, ...data.inline].filter(
      (s) => s.kind === 'source' || (s.kind === 'inline' && !s.dynamic)
    )
    if (!files.length) continue
    imports.push(`\n/* ${data.name} (${slug}) */`)
    for (const f of files) imports.push(`@import url('./${f.file}');`)
  }
  return `/*!
 * Karibase Plugins Layer — ${GENERATED_BANNER}
 *
 * Single entry point that layers every extracted plugin stylesheet on top of
 * the Karibase core. Vendor duplicates (compiled Tailwind, *.min.css) and
 * PHP-interpolated inline blocks are extracted but intentionally not imported.
 *
 * Usage:
 *   <link rel="stylesheet" href="css/karibase.css">
 *   <link rel="stylesheet" href="css/karibase-plugins.css">
 *
 * Regenerate with: npm run extract:plugins
 */
${imports.join('\n')}
`
}

async function main() {
  console.log('Karibase — extracting plugin styles')
  console.log(`Plugins dir: ${PLUGINS_DIR}`)

  if (!existsSync(PLUGINS_DIR)) {
    console.error(`Plugins directory not found: ${PLUGINS_DIR}`)
    console.error('Set PLUGINS_DIR to your wp-content/plugins path.')
    process.exit(1)
  }

  await rm(OUT_STYLES, { recursive: true, force: true })

  const plugins = {}
  const entries = await readdir(PLUGINS_DIR, { withFileTypes: true })
  for (const entry of entries) {
    if (!entry.isDirectory() || SKIP_DIRS.has(entry.name)) continue
    const dir = path.join(PLUGINS_DIR, entry.name)
    if (!(await isPluginDir(dir))) continue
    const { styles, inline } = await extractPlugin(dir)
    if (!styles.length && !inline.length) continue
    plugins[entry.name] = {
      name: entry.name.replace(/(^|[-_])\w/g, (m) => m.toUpperCase()).replace(/[-_]/g, ' '),
      styles,
      inline
    }
    console.log(`  ${entry.name}: ${styles.length} css + ${inline.length} inline`)
  }

  await mkdir(path.dirname(OUT_REGISTRY), { recursive: true })
  await writeFile(OUT_REGISTRY, registryModule(plugins))
  await writeFile(OUT_REGISTRY_JSON, JSON.stringify({ generated: new Date().toISOString(), plugins }, null, 2))
  await writeFile(OUT_INDEX, indexCss(plugins))

  const totals = Object.values(plugins).reduce(
    (acc, p) => ({
      css: acc.css + p.styles.length,
      inline: acc.inline + p.inline.length
    }),
    { css: 0, inline: 0 }
  )
  console.log(`\nDone: ${Object.keys(plugins).length} plugins, ${totals.css} stylesheets, ${totals.inline} inline blocks`)
  console.log(`Index:    ${path.relative(ROOT, OUT_INDEX)}`)
  console.log(`Registry: ${path.relative(ROOT, OUT_REGISTRY)}`)
}

main().catch((err) => {
  console.error('Extraction failed:', err)
  process.exit(1)
})
